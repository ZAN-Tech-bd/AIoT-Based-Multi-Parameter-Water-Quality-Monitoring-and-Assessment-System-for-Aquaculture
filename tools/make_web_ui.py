#!/usr/bin/env python3
"""Build firmware/WaterQualityMonitor/web_ui.h from web/index.html.

Usage: python3 tools/make_web_ui.py
Keep index.html and web_ui.h in sync so USB and Wi-Fi modes use the same dashboard.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
DST = ROOT / "firmware" / "WaterQualityMonitor" / "web_ui.h"
DELIM = "AQUAUI"
MAX_LITERAL = 60000  # keep each raw-string chunk well below MSVC-style limits; GCC has none, split anyway for safety


def build_header(html: str) -> str:
    if (")" + DELIM + '"') in html:
        sys.exit("ERROR: raw-string delimiter occurs inside the HTML.")
    # split on line boundaries into adjacent raw-string literals (concatenated by the compiler)
    chunks, cur = [], ""
    for line in html.splitlines(keepends=True):
        if len(cur) + len(line) > MAX_LITERAL and cur:
            chunks.append(cur); cur = ""
        cur += line
    if cur:
        chunks.append(cur)
    lit = "\n".join('R"%s(%s)%s"' % (DELIM, c, DELIM) for c in chunks)
    return (
        "// AUTO-GENERATED by make_web_ui.py from index.html - do not edit by hand.\n"
        "// Dashboard served by the ESP32 at http://192.168.4.1/\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "const char WEB_UI_HTML[] PROGMEM =\n" + lit + ";\n\n"
        "const size_t WEB_UI_HTML_LEN = sizeof(WEB_UI_HTML) - 1;\n"
    )


def main():
    html = SRC.read_text(encoding="utf-8")
    if "</script" not in html.lower():
        sys.exit("ERROR: index.html does not contain a script block.")
    hdr = build_header(html)
    DST.write_text(hdr, encoding="utf-8")
    print("web_ui.h: %d bytes" % len(hdr.encode()))


if __name__ == "__main__":
    main()
